"""ボートレース場コード（公式の場コード 01〜24）。"""

VENUES = {
    "01": "桐生", "02": "戸田", "03": "江戸川", "04": "平和島", "05": "多摩川",
    "06": "浜名湖", "07": "蒲郡", "08": "常滑", "09": "津", "10": "三国",
    "11": "びわこ", "12": "住之江", "13": "尼崎", "14": "鳴門", "15": "丸亀",
    "16": "児島", "17": "宮島", "18": "徳山", "19": "下関", "20": "若松",
    "21": "芦屋", "22": "福岡", "23": "唐津", "24": "大村",
}
NAME_TO_CODE = {v: k for k, v in VENUES.items()}


def venue_code(v: str) -> str:
    """'12' / '住之江' / 12 のどれでも場コード2桁にする。"""
    s = str(v).strip()
    if s in NAME_TO_CODE:
        return NAME_TO_CODE[s]
    if s.isdigit() and 1 <= int(s) <= 24:
        return f"{int(s):02d}"
    raise ValueError(f"不明なレース場: {v}")
